// Helper to calculate Average score based on Circular 22/58 rule:
// TBM = (Tong_TX + MidTerm * 2 + Final * 3) / (Count_TX + 2 + 3)
export function calculateSubjectAverage(entry: Partial<GradeEntry>): number | undefined {
  const txValues = [entry.tx1, entry.tx2, entry.tx3, entry.tx4].filter((v): v is number => typeof v === 'number' && !isNaN(v));
  const hasMid = typeof entry.midTerm === 'number' && !isNaN(entry.midTerm);
  const hasFinal = typeof entry.finalExam === 'number' && !isNaN(entry.finalExam);

  if (txValues.length === 0 && !hasMid && !hasFinal) {
    return undefined;
  }

  let totalWeight = txValues.length;
  let weightedSum = txValues.reduce((acc, curr) => acc + curr, 0);

  if (hasMid) {
    weightedSum += (entry.midTerm as number) * 2;
    totalWeight += 2;
  }

  if (hasFinal) {
    weightedSum += (entry.finalExam as number) * 3;
    totalWeight += 3;
  }

  if (totalWeight === 0) return undefined;
  const avg = weightedSum / totalWeight;
  return Math.round(avg * 10) / 10;
}

